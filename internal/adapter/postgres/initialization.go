// This is the bcrypt hash of the intentionally public bootstrap password
// Daydream123456, never a password or dump from a running installation.
const initialOperatorPasswordHash = "$2a$10$zARRPb2R7CVEOnmMJpwLiuLWRH7Sttl7whU0G9e2zndqXgyxx2uia"

func initialOperatorSQL() string {
	return fmt.Sprintf(`-- A populated installation never receives another account or a password reset.
LOCK TABLE drama_catalog_v1.users IN SHARE ROW EXCLUSIVE MODE;
INSERT INTO drama_catalog_v1.users(id,email,username,role,password_hash)
SELECT 'daydream-initial-operator','%s','%s','operator',convert_to('%s','UTF8')
WHERE NOT EXISTS (SELECT 1 FROM drama_catalog_v1.users)
ON CONFLICT DO NOTHING;
`, accounts.InitialOperatorEmail, accounts.InitialOperatorUsername, initialOperatorPasswordHash)
}

// InitializationSQL generates the distributable empty-database SQL from the
// same schema and bootstrap seed used by the application, without reading a DB.
func InitializationSQL() string {
	return `-- Generated by go generate ./internal/adapter/postgres; do not edit.
-- Initial login: Daydream / Daydream123456. Change the password after first login.
BEGIN;
SELECT pg_advisory_xact_lock(hashtextextended('drama-agent:schema',0));
` + schemaSQL + "\nSELECT pg_advisory_xact_lock(hashtextextended('drama-agent:operator-init',0));\n" + initialOperatorSQL() + "COMMIT;\n"
}

// InitializeDefaultOperator is the normal deployment bootstrap. Any existing
// user makes it a no-op; explicit maintenance initialization stays separate.
func (s *Store) InitializeDefaultOperator(ctx context.Context) (bool, error) {
	tx, err := s.pool.Begin(ctx)
	if err != nil {
		return false, err
	}
	defer tx.Rollback(context.WithoutCancel(ctx))
	if _, err = tx.Exec(ctx, `SELECT pg_advisory_xact_lock(hashtextextended('drama-agent:operator-init',0))`); err != nil {
		return false, err
	}
	result, err := tx.Exec(ctx, initialOperatorSQL())
	if err != nil {
		return false, err
	}
	if err = tx.Commit(ctx); err != nil {
		return false, err
	}
	return result.RowsAffected() == 1, nil
}
