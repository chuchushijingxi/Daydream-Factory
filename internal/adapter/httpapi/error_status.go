package httpapi

// commandStatus 将稳定错误码映射到 HTTP；领域错误不依赖传输状态。
func commandStatus(code string) int {
	switch code {
	case "RUNTIME_UNAVAILABLE":
		return 503
	case "LEASE_LOST":
		return 409
	case "PLATFORM_SETTINGS_INVALID", "INVALID_PLATFORM_LOGO":
		return 400
	case "PLATFORM_SETTINGS_CONFLICT":
		return 409
	case "PLATFORM_SETTINGS_SAVE_UNKNOWN", "PLATFORM_SETTINGS_UNAVAILABLE":
		return 503
	case "CREDIT_UPDATES_UNAVAILABLE":
		return 503
	case "AUTH_REQUIRED", "SESSION_EXPIRED", "SESSION_REPLACED", "SESSION_REVOKED", "ACCOUNT_DISABLED", "INVALID_CREDENTIALS":
		return 401
	case "SESSION_AUDIENCE_MISMATCH", "ROLE_FORBIDDEN", "REGISTRATION_FORBIDDEN":
		return 403
	case "INVALID_SESSION_AUDIENCE", "NOTIFICATION_IMAGE_INVALID", "NOTIFICATION_INVALID", "CREDIT_POLICY_INVALID", "MAIL_CONFIGURATION_INVALID", "INVALID_USERNAME", "INVALID_AVATAR", "CURRENT_PASSWORD_INVALID", "INVALID_PASSWORD", "INVALID_VERIFICATION_CODE", "CREDIT_INVALID_AMOUNT", "CREDIT_INVALID_CATEGORY":
		return 400
	case "AUTH_RATE_LIMITED":
		return 429
	case "NOTIFICATION_CONFLICT", "NOTIFICATION_COMMAND_CONFLICT", "CREDIT_POLICY_CONFLICT", "MAIL_CONFIGURATION_CONFLICT", "EMAIL_EXISTS", "AUTHORIZATION_CODE_INVALID", "SELF_DISABLE_FORBIDDEN", "INITIAL_IDENTITY_CONFLICT", "CREDIT_INSUFFICIENT", "CREDIT_IDEMPOTENCY_CONFLICT", "CREDIT_REFUND_EXCEEDED":
		return 409
	case "REGISTRATION_COMMIT_UNKNOWN", "NOTIFICATION_UNAVAILABLE", "NOTIFICATION_COMMIT_UNKNOWN", "CREDIT_POLICY_UNAVAILABLE", "CREDIT_POLICY_SAVE_UNKNOWN", "CREDIT_QUERY_UNAVAILABLE", "CREDIT_TOTAL_OVERFLOW", "MAIL_CONFIGURATION_UNAVAILABLE", "MAIL_CONFIG_SAVE_UNKNOWN", "AUTH_UNAVAILABLE", "MAIL_UNAVAILABLE", "MAIL_DELIVERY_FAILED", "CREDIT_COMMIT_UNKNOWN":
		return 503
	case "THUMBNAIL_UNSUPPORTED", "INVALID_IMAGE", "INVALID_ASSET_IMAGE":
		return 400
	case "FILE_CORRUPT", "THUMBNAIL_FAILED":
		return 502
	case "FILE_STORAGE_UNAVAILABLE", "THUMBNAIL_UNAVAILABLE":
		return 503
	case "INVALID_MODEL_LOGO", "INVALID_MODEL_PROFILE", "INVALID_MODEL_URL", "MODEL_KEY_REQUIRED", "MOCK_MODEL_REQUIRED":
		return 400
	case "EXECUTION_NOT_AUTHORIZED", "SERVICE_READ_ONLY":
		return 403
	case "EPISODE_INDEX_REQUIRED", "EPISODE_INDEX_NOT_RETRYABLE", "STORYBOARD_UP_TO_DATE", "EPISODE_RANGE_STALE", "STORYBOARD_REQUIRED", "STORYBOARD_INCOMPLETE", "VISUAL_PROMPTS_REQUIRED", "ASSETS_UP_TO_DATE", "MODEL_RESULT_UNKNOWN", "BASE_PROMPT_REQUIRED", "MODEL_NOT_SELECTED", "ASSETS_NOT_READY", "CATALOG_USER_EDITED", "MODEL_IN_USE", "OFFICIAL_CONNECTION_FIXED", "OUTLINE_ALREADY_STARTED", "PROJECT_FAILED", "RUN_ACTIVE", "SETTINGS_LOCKED", "SOURCE_LOCKED", "STYLE_LOCKED", "STYLE_VERSION_CONFLICT", "VISUAL_PROMPTS_ALREADY_STARTED", "VISUAL_PROMPTS_UP_TO_DATE":
		return 409
	case "REQUEST_TOO_LARGE":
		return 413
	case "BUILTIN_CONNECTION_FIXED":
		return 409
	case "COMMAND_ID_CONFLICT", "TASK_ACTIVE", "TASK_TERMINAL", "MEDIA_OUTPUT_STALE", "VIDEO_PROMPT_REQUIRED", "ASSET_IMAGE_EXISTS":
		return 409
	case "MEDIA_OPTIONS_INVALID", "IMAGE_TYPE_INVALID", "IMAGE_ASPECT_RATIO_INVALID":
		return 400
	case "MEDIA_PROFILE_UNAVAILABLE", "MODEL_PRICE_UNAVAILABLE":
		return 503
	case "BILLING_BASIS_CHANGED", "VIDEO_MODEL_UNAVAILABLE", "SHOT_DURATION_REQUIRED", "SHOT_DURATION_EXCEEDED":
		return 409
	case "TASK_UNAVAILABLE", "TASK_PROTOCOL_UNSUPPORTED":
		return 503
	case "MOCK_GENERATION_FAILED":
		return 502
	case "SCRIPT_FILE_CORRUPT", "MODEL_DIRECTORY_FAILED", "MODEL_USAGE_INVALID":
		return 502
	case "SCRIPT_STORAGE_UNAVAILABLE", "MODEL_CONFIG_UNAVAILABLE":
		return 503
	default:
		return 500
	}
}
